#!/usr/bin/env python3
"""
Two-agent pipeline demo.

Prerequisites:
    1. Install and log in to the API once (see the top-level README).
    2. Generate a deployment:
           ./tools/make-multi-agent.sh ~/my-project --agents 2
    3. Start the agents:
           cd ~/my-project/deepseek-agents
           ./scripts/start-all.sh

Run:
    python demo_client.py --deployment ~/my-project/deepseek-agents

The pipeline:
    1/4  Researcher gathers facts about the topic.
    2/4  Writer drafts a two-paragraph introduction from those facts.
    3/4  Researcher critiques the draft.
    4/4  Writer revises based on the critique.

Both agents run as independent processes with their own chats. The
only thing they share is the DeepSeek cookie session. The client
treats them as two separate OpenAI-compatible HTTP endpoints.

Uses only the Python standard library — no external dependencies.
"""

import argparse
import json
import socket
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any


# ---- HTTP helpers ---------------------------------------------------

def http_post(url: str, body: dict[str, Any], headers: dict[str, str],
              timeout: float) -> tuple[int, str]:
    """
    POST JSON to `url`, return (status_code, response_body_text).

    On HTTP error responses (4xx, 5xx), returns the status code and
    the body rather than raising — the caller handles every status
    explicitly.
    """
    data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, method="POST")
    for key, value in headers.items():
        req.add_header(key, value)
    req.add_header("Content-Type", "application/json")

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, resp.read().decode("utf-8")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", errors="replace")
    except urllib.error.URLError:
        raise


def http_get(url: str, headers: dict[str, str],
             timeout: float) -> tuple[int, str]:
    """GET `url`, return (status_code, response_body_text)."""
    req = urllib.request.Request(url, method="GET")
    for key, value in headers.items():
        req.add_header(key, value)

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, resp.read().decode("utf-8")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", errors="replace")
    except urllib.error.URLError:
        raise


def is_port_open(port: int, timeout: float = 2.0) -> bool:
    """Return True if a TCP connect to 127.0.0.1:port succeeds quickly."""
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=timeout):
            return True
    except OSError:
        return False


# ---- deployment loading ---------------------------------------------

def read_kv(path: Path, key: str) -> str:
    """Read a single KEY=value from an env file."""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(key + "="):
            return line.split("=", 1)[1].strip()
    raise KeyError(f"{key} not found in {path}")


def load_agents(deployment: Path) -> list[dict[str, Any]]:
    """
    Find every agent-N directory in a generated deployment and read
    its port and API key. Returns them sorted by directory name, so
    agent-1 is first, agent-2 second, and so on.
    """
    agents_dir = deployment / "agents"
    if not agents_dir.is_dir():
        sys.exit(
            f"✗ {agents_dir} not found.\n"
            f"  Is {deployment} a directory generated by make-multi-agent.sh?"
        )

    agents: list[dict[str, Any]] = []
    for agent_dir in sorted(agents_dir.iterdir()):
        if not agent_dir.is_dir():
            continue
        env_file = agent_dir / "agent.env"
        key_file = agent_dir / ".api-key"
        if not env_file.exists() or not key_file.exists():
            continue

        agents.append({
            "name": agent_dir.name,
            "dir": agent_dir,
            "port": int(read_kv(env_file, "PORT")),
            "key": key_file.read_text(encoding="utf-8").strip(),
        })

    if len(agents) < 2:
        sys.exit(
            f"✗ Need at least 2 agents, found {len(agents)} in {agents_dir}\n"
            f"  Generate with: make-multi-agent.sh <dir> --agents 2"
        )

    return agents


# ---- readiness ------------------------------------------------------

def wait_for_ready(agent: dict[str, Any], timeout: int = 180) -> bool:
    """
    Poll /v1/context/status until the agent's DeepSeek client is
    initialised.

    Two-stage check:
      1. TCP connect to the port — fails fast if the agent was never
         started. Returns False in ~2 seconds instead of waiting for
         the full timeout.
      2. /v1/context/status — waits for the DeepSeek client itself,
         which comes up 15–30 seconds after the HTTP port opens
         (Chromium launch, navigation, selector check).
    """
    port = int(agent["port"])

    # Stage 1: nothing listening → fail immediately with a clear message.
    if not is_port_open(port):
        print(f"   ✗ {agent['name']}: port {port} is closed", file=sys.stderr)
        print(f"     Start the agents first: "
              f"cd <deployment> && ./scripts/start-all.sh", file=sys.stderr)
        return False

    # Stage 2: wait for the client to become ready.
    url = f"http://127.0.0.1:{port}/v1/context/status"
    headers = {"Authorization": f"Bearer {agent['key']}"}
    deadline = time.time() + timeout

    while time.time() < deadline:
        try:
            status, _ = http_get(url, headers, timeout=5.0)
            if status == 200:
                return True
            if status == 401:
                print(f"   ✗ {agent['name']} rejected its API key",
                      file=sys.stderr)
                return False
            # 503 → still initialising
        except (urllib.error.URLError, socket.timeout, TimeoutError):
            pass
        time.sleep(1)

    return False


# ---- core -----------------------------------------------------------

def ask(agent: dict[str, Any], content: str, retries: int = 3) -> str:
    """
    Send a message to one agent, handling every recoverable HTTP
    code per the client protocol. Returns the assistant text.
    """
    port = int(agent["port"])
    url = f"http://127.0.0.1:{port}/v1/chat/completions"
    headers = {"Authorization": f"Bearer {agent['key']}"}
    payload: dict[str, Any] = {
        "messages": [{"role": "user", "content": content}],
    }

    backoff = 1.0
    attempt = 0

    while True:
        attempt += 1

        try:
            status, body_text = http_post(url, payload, headers, timeout=300.0)
        except (urllib.error.URLError, socket.timeout, TimeoutError):
            if attempt > retries:
                raise TimeoutError(f"{agent['name']} timed out")
            print(f"   ⏱  {agent['name']} timed out, retry in {backoff:.0f}s...")
            time.sleep(backoff)
            backoff *= 2
            continue

        # ---- 200 OK ---------------------------------------------
        if status == 200:
            data = json.loads(body_text)
            status_block = data.get("context_status") or {}
            _print_context(agent["name"], status_block)
            return data["choices"][0]["message"]["content"]

        # ---- 400 bad request -----------------------------------
        if status == 400:
            raise RuntimeError(
                f"{agent['name']} rejected the request: {body_text}"
            )

        # ---- 401 invalid key -----------------------------------
        if status == 401:
            raise RuntimeError(
                f"{agent['name']} rejected the API key.\n"
                f"  Key file: {agent['dir'] / '.api-key'}"
            )

        # ---- 409 context exhausted -----------------------------
        if status == 409:
            err: dict[str, Any] = {}
            try:
                err = json.loads(body_text).get("error", {})
            except (ValueError, AttributeError):
                pass
            print(f"   ⚠  {agent['name']} context exhausted "
                  f"({err.get('chars_used')}/{err.get('chars_limit')})")
            print(f"   →  starting fresh chat and retrying")
            http_post(
                f"http://127.0.0.1:{port}/v1/chat/new",
                {"restore": False},
                headers,
                timeout=120.0,
            )
            attempt -= 1  # retry does not count against the budget
            continue

        # ---- 503 two distinct causes ---------------------------
        #   {"error": {"type": "server_busy"}}   → fatal, agent exits
        #   {"error": "Client not ready. ..."}   → transient, retry
        if status == 503:
            try:
                body = json.loads(body_text)
            except ValueError:
                body = {"raw": body_text[:400]}

            err_field = body.get("error")
            if isinstance(err_field, dict) and err_field.get("type") == "server_busy":
                raise RuntimeError(
                    f"{agent['name']} reported server busy. The agent "
                    f"shuts down by design — wait and restart."
                )

            msg = err_field if isinstance(err_field, str) else str(body)
            if attempt > retries:
                raise RuntimeError(f"{agent['name']} not ready: {body}")
            print(f"   ⏱  {agent['name']} not ready ({msg}), "
                  f"retry in {backoff:.0f}s...")
            time.sleep(backoff)
            backoff *= 2
            continue

        # ---- 504 timeout ---------------------------------------
        if status == 504:
            if attempt > retries:
                raise TimeoutError(f"{agent['name']} timed out")
            print(f"   ⏱  {agent['name']} returned 504, "
                  f"retry in {backoff:.0f}s...")
            time.sleep(backoff)
            backoff *= 2
            continue

        raise RuntimeError(
            f"{agent['name']} returned HTTP {status}: {body_text}"
        )


def _print_context(name: str, status: dict[str, Any]) -> None:
    if not status:
        return
    used = status.get("chars_used", 0)
    limit = status.get("chars_limit", 0)
    pct = status.get("percent_used", 0)
    print(f"   [{name}] context: {used:,} / {limit:,} chars ({pct}%)")
    warning = status.get("warning")
    if warning:
        print(f"   [{name}] ⚠  {warning} → {status.get('recommendation')}")


# ---- pipeline -------------------------------------------------------

def run_pipeline(researcher: dict[str, Any],
                 writer: dict[str, Any],
                 topic: str) -> str:
    print(f"Topic: {topic}")
    print()

    print("1/4  Researcher: gather three facts")
    facts = ask(
        researcher,
        f"List three concrete, verifiable facts about {topic}. "
        f"Be terse — plain list, no preamble.",
    )
    print(f"     → {facts[:120]}{'...' if len(facts) > 120 else ''}")
    print()

    print("2/4  Writer: draft an introduction")
    draft = ask(
        writer,
        f"Write a two-paragraph introduction about {topic} "
        f"using these facts:\n\n{facts}",
    )
    print(f"     → {draft[:120]}{'...' if len(draft) > 120 else ''}")
    print()

    print("3/4  Researcher: critique the draft")
    critique = ask(
        researcher,
        f"Here is a draft introduction about {topic}:\n\n{draft}\n\n"
        f"Point out any factual errors or unsupported claims in a "
        f"short bullet list. If there are none, say so.",
    )
    print(f"     → {critique[:120]}{'...' if len(critique) > 120 else ''}")
    print()

    print("4/4  Writer: revise based on the critique")
    revision = ask(
        writer,
        f"Revise this introduction, addressing the critique:\n\n"
        f"Draft:\n{draft}\n\nCritique:\n{critique}",
    )
    print()

    return revision


# ---- entry ----------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run a two-agent researcher/writer pipeline.",
    )
    parser.add_argument(
        "--deployment",
        default="./deepseek-agents",
        help="path to a directory generated by make-multi-agent.sh "
             "(default: ./deepseek-agents)",
    )
    parser.add_argument(
        "--topic",
        default="the Fermi paradox",
        help="topic for the pipeline (default: %(default)s)",
    )
    args = parser.parse_args()

    deployment = Path(args.deployment).expanduser().resolve()
    if not deployment.is_dir():
        print(f"✗ Deployment not found: {deployment}", file=sys.stderr)
        print(f"  Generate one with:", file=sys.stderr)
        print(f"      make-multi-agent.sh <dir> --agents 2", file=sys.stderr)
        return 1

    agents = load_agents(deployment)
    researcher, writer = agents[0], agents[1]
    print(f"Deployment: {deployment}")
    print(f"  researcher: {researcher['name']}  port {researcher['port']}")
    print(f"  writer:     {writer['name']}  port {writer['port']}")
    print()

    print("Checking readiness...")
    for agent in (researcher, writer):
        print(f"  {agent['name']}: ", end="", flush=True)
        if not wait_for_ready(agent):
            print("✗")
            print(f"  Start the agents first: "
                  f"cd {deployment} && ./scripts/start-all.sh",
                  file=sys.stderr)
            return 1
        print("✓")
    print()

    t0 = time.time()
    try:
        final = run_pipeline(researcher, writer, args.topic)
    except Exception as e:
        print(f"\n✗ Pipeline failed: {e}", file=sys.stderr)
        return 1

    elapsed = time.time() - t0

    print("=" * 60)
    print("Final revision:")
    print("=" * 60)
    print(final)
    print("=" * 60)
    print(f"Total wall time: {elapsed:.1f}s")

    return 0


if __name__ == "__main__":
    sys.exit(main())