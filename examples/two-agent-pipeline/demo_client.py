#!/usr/bin/env python3
"""
Two-agent pipeline demo.

Prerequisites:
    1. Install and log in to the API once (see the top-level README).
    2. Generate a deployment:
           ./tools/make-multi-agent.sh ~/my-project --agents 2
    3. Start the agents:
           cd ~/my-project/deepseek-agents
           ./scripts/start-all.sh

Run:
    python demo_client.py --deployment ~/my-project/deepseek-agents

The pipeline:
    1/4  Researcher gathers facts about the topic.
    2/4  Writer drafts a two-paragraph introduction from those facts.
    3/4  Researcher critiques the draft.
    4/4  Writer revises based on the critique.

Both agents run as independent processes with their own chats. The
only thing they share is the DeepSeek cookie session. The client
treats them as two separate OpenAI-compatible HTTP endpoints.
"""

import argparse
import sys
import time
from pathlib import Path

import requests


# ---- deployment loading ---------------------------------------------

def read_kv(path: Path, key: str) -> str:
    """Read a single KEY=value from an env file."""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(key + "="):
            return line.split("=", 1)[1].strip()
    raise KeyError(f"{key} not found in {path}")


def load_agents(deployment: Path):
    """
    Find every agent-N directory in a generated deployment and read
    its port and API key. Returns them sorted by directory name, so
    agent-1 is first, agent-2 second, and so on.
    """
    agents_dir = deployment / "agents"
    if not agents_dir.is_dir():
        sys.exit(
            f"✗ {agents_dir} not found.\n"
            f"  Is {deployment} a directory generated by make-multi-agent.sh?"
        )

    agents = []
    for agent_dir in sorted(agents_dir.iterdir()):
        if not agent_dir.is_dir():
            continue
        env_file = agent_dir / "agent.env"
        key_file = agent_dir / ".api-key"
        if not env_file.exists() or not key_file.exists():
            continue

        agents.append({
            "name": agent_dir.name,
            "dir": agent_dir,
            "port": int(read_kv(env_file, "PORT")),
            "key": key_file.read_text(encoding="utf-8").strip(),
        })

    if len(agents) < 2:
        sys.exit(
            f"✗ Need at least 2 agents, found {len(agents)} in {agents_dir}\n"
            f"  Generate with: make-multi-agent.sh <dir> --agents 2"
        )

    return agents


# ---- readiness ------------------------------------------------------

def wait_for_ready(agent: dict, timeout: int = 180) -> bool:
    """
    Poll /v1/context/status until the agent's DeepSeek client is
    initialised. A live HTTP port is not enough — the client comes
    up 15–30 seconds later, after Chromium launch and the selector
    check.
    """
    url = f"http://localhost:{agent['port']}/v1/context/status"
    deadline = time.time() + timeout

    while time.time() < deadline:
        try:
            r = requests.get(
                url,
                headers={"Authorization": f"Bearer {agent['key']}"},
                timeout=5,
            )
            if r.status_code == 200:
                return True
            if r.status_code == 401:
                print(f"   ✗ {agent['name']} rejected its API key",
                      file=sys.stderr)
                return False
            # 503 → still initialising
        except requests.RequestException:
            pass
        time.sleep(1)

    return False


# ---- core -----------------------------------------------------------

def ask(agent: dict, content: str, retries: int = 3) -> str:
    """
    Send a message to one agent, handling every recoverable HTTP
    code per the client protocol. Returns the assistant text.
    """
    url = f"http://localhost:{agent['port']}/v1/chat/completions"
    backoff = 1.0
    attempt = 0

    while True:
        attempt += 1

        try:
            r = requests.post(
                url,
                headers={
                    "Authorization": f"Bearer {agent['key']}",
                    "Content-Type": "application/json",
                },
                json={"messages": [{"role": "user", "content": content}]},
                timeout=300,
            )
        except requests.Timeout:
            if attempt > retries:
                raise TimeoutError(f"{agent['name']} timed out")
            print(f"   ⏱  {agent['name']} timed out, retry in {backoff:.0f}s...")
            time.sleep(backoff)
            backoff *= 2
            continue

        # ---- 200 OK ---------------------------------------------
        if r.status_code == 200:
            data = r.json()
            _print_context(agent["name"], data.get("context_status", {}))
            return data["choices"][0]["message"]["content"]

        # ---- 400 bad request -----------------------------------
        if r.status_code == 400:
            raise RuntimeError(f"{agent['name']} rejected the request: {r.text}")

        # ---- 401 invalid key -----------------------------------
        if r.status_code == 401:
            raise RuntimeError(
                f"{agent['name']} rejected the API key.\n"
                f"  Key file: {agent['dir'] / '.api-key'}"
            )

        # ---- 409 context exhausted -----------------------------
        if r.status_code == 409:
            err = r.json().get("error", {})
            print(f"   ⚠  {agent['name']} context exhausted "
                  f"({err.get('chars_used')}/{err.get('chars_limit')})")
            print(f"   →  starting fresh chat and retrying")
            requests.post(
                f"http://localhost:{agent['port']}/v1/chat/new",
                headers={
                    "Authorization": f"Bearer {agent['key']}",
                    "Content-Type": "application/json",
                },
                json={"restore": False},
                timeout=120,
            )
            attempt -= 1  # retry does not count against the budget
            continue

        # ---- 503 two distinct causes ---------------------------
        #   {"error": {"type": "server_busy"}}   → fatal, agent exits
        #   {"error": "Client not ready. ..."}   → transient, retry
        if r.status_code == 503:
            try:
                body = r.json()
            except Exception:
                body = {"raw": r.text[:400]}

            err_field = body.get("error")
            if isinstance(err_field, dict) and err_field.get("type") == "server_busy":
                raise RuntimeError(
                    f"{agent['name']} reported server busy. The agent "
                    f"shuts down by design — wait and restart."
                )

            msg = err_field if isinstance(err_field, str) else str(body)
            if attempt > retries:
                raise RuntimeError(f"{agent['name']} not ready: {body}")
            print(f"   ⏱  {agent['name']} not ready ({msg}), retry in {backoff:.0f}s...")
            time.sleep(backoff)
            backoff *= 2
            continue

        # ---- 504 timeout ---------------------------------------
        if r.status_code == 504:
            if attempt > retries:
                raise TimeoutError(f"{agent['name']} timed out")
            print(f"   ⏱  {agent['name']} returned 504, retry in {backoff:.0f}s...")
            time.sleep(backoff)
            backoff *= 2
            continue

        raise RuntimeError(
            f"{agent['name']} returned HTTP {r.status_code}: {r.text}"
        )


def _print_context(name: str, status: dict) -> None:
    if not status:
        return
    used = status.get("chars_used", 0)
    limit = status.get("chars_limit", 0)
    pct = status.get("percent_used", 0)
    print(f"   [{name}] context: {used:,} / {limit:,} chars ({pct}%)")
    warning = status.get("warning")
    if warning:
        print(f"   [{name}] ⚠  {warning} → {status.get('recommendation')}")


# ---- pipeline -------------------------------------------------------

def run_pipeline(researcher: dict, writer: dict, topic: str) -> str:
    print(f"Topic: {topic}")
    print()

    print("1/4  Researcher: gather three facts")
    facts = ask(
        researcher,
        f"List three concrete, verifiable facts about {topic}. "
        f"Be terse — plain list, no preamble.",
    )
    print(f"     → {facts[:120]}{'...' if len(facts) > 120 else ''}")
    print()

    print("2/4  Writer: draft an introduction")
    draft = ask(
        writer,
        f"Write a two-paragraph introduction about {topic} "
        f"using these facts:\n\n{facts}",
    )
    print(f"     → {draft[:120]}{'...' if len(draft) > 120 else ''}")
    print()

    print("3/4  Researcher: critique the draft")
    critique = ask(
        researcher,
        f"Here is a draft introduction about {topic}:\n\n{draft}\n\n"
        f"Point out any factual errors or unsupported claims in a "
        f"short bullet list. If there are none, say so.",
    )
    print(f"     → {critique[:120]}{'...' if len(critique) > 120 else ''}")
    print()

    print("4/4  Writer: revise based on the critique")
    revision = ask(
        writer,
        f"Revise this introduction, addressing the critique:\n\n"
        f"Draft:\n{draft}\n\nCritique:\n{critique}",
    )
    print()

    return revision


# ---- entry ----------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run a two-agent researcher/writer pipeline.",
    )
    parser.add_argument(
        "--deployment",
        default="./deepseek-agents",
        help="path to a directory generated by make-multi-agent.sh "
             "(default: ./deepseek-agents)",
    )
    parser.add_argument(
        "--topic",
        default="the Fermi paradox",
        help="topic for the pipeline (default: %(default)s)",
    )
    args = parser.parse_args()

    deployment = Path(args.deployment).expanduser().resolve()
    if not deployment.is_dir():
        print(f"✗ Deployment not found: {deployment}", file=sys.stderr)
        print(f"  Generate one with:", file=sys.stderr)
        print(f"      make-multi-agent.sh <dir> --agents 2", file=sys.stderr)
        return 1

    agents = load_agents(deployment)
    researcher, writer = agents[0], agents[1]
    print(f"Deployment: {deployment}")
    print(f"  researcher: {researcher['name']}  port {researcher['port']}")
    print(f"  writer:     {writer['name']}  port {writer['port']}")
    print()

    print("Checking readiness...")
    for agent in (researcher, writer):
        print(f"  {agent['name']}: ", end="", flush=True)
        if not wait_for_ready(agent):
            print("✗")
            print(f"  Start the agents first: cd {deployment} && ./scripts/start-all.sh",
                  file=sys.stderr)
            return 1
        print("✓")
    print()

    t0 = time.time()
    try:
        final = run_pipeline(researcher, writer, args.topic)
    except Exception as e:
        print(f"\n✗ Pipeline failed: {e}", file=sys.stderr)
        return 1

    elapsed = time.time() - t0

    print("=" * 60)
    print("Final revision:")
    print("=" * 60)
    print(final)
    print("=" * 60)
    print(f"Total wall time: {elapsed:.1f}s")

    return 0


if __name__ == "__main__":
    sys.exit(main())